"""Write the game in Ludii's game description language: docs/ludii/Tactical Formation.lud.

Ludii (https://ludii.games) is a general game system with a large library of
traditional games. The board, starting positions and turn order are taken
from core/modes.py, so the Ludii version always matches this game.

The board is a graph: grid points joined along the grid lines, and each
square's centre joined to its four corners. Ludii follows straight lines
through these joints, so a grid point jumps diagonally over a centre to the
opposite corner, a centre jumps over a corner to the next centre, and a
diagonal capture line alternates between the two layers — as in the game.

A turn has one or two steps: jump; then, if lines are sandwiched, click your
own piece at the far end of the line to flip (one line only, as the folk
rule says). Run with: uv run python tools/make_ludii.py
"""

import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from core.modes import MODE_PLAY_2, MODE_PLAY_3_HUMAN, MODE_PLAY_4_HUMAN  # noqa: E402

OUT = os.path.join(REPO, 'docs', 'ludii', 'Tactical Formation.lud')
MODES = {2: MODE_PLAY_2, 3: MODE_PLAY_3_HUMAN, 4: MODE_PLAY_4_HUMAN}
RGB = {'green': (50, 205, 50), 'yellow': (230, 200, 0),
       'purple': (170, 70, 210), 'blue': (40, 120, 230)}


def points(mode):
    """Board points in Ludii's vertex order: grid points and centres, row by row."""
    out = []
    for row in range(2 * mode.board_height + 1):
        y = row / 2
        for col in range(2 * mode.board_width + 1):
            x = col / 2
            if (x % 1 == 0) != (y % 1 == 0):
                continue                     # not a grid point nor a centre
            if x % 1 and (x > mode.board_width or y > mode.board_height):
                continue
            if (x, y) in mode.excluded_cells:
                continue
            out.append((x, y))
    return out


def edges(pts):
    index = {p: i for i, p in enumerate(pts)}
    out = []
    for (x, y), i in index.items():
        if x % 1 == 0:                       # grid lines between grid points
            for nxt in ((x + 1, y), (x, y + 1)):
                if nxt in index:
                    out.append((i, index[nxt]))
        else:                                # a centre to its four corners
            for corner in ((x - .5, y - .5), (x + .5, y - .5), (x - .5, y + .5), (x + .5, y + .5)):
                if corner in index:
                    out.append((i, index[corner]))
    return out


def _num(v):
    return str(int(v)) if v == int(v) else str(v)


def board(mode):
    pts = points(mode)
    # Ludii's y axis points up; doubling keeps every coordinate a whole number.
    vertices = ' '.join(f'{{{_num(2 * x)} {_num(2 * (mode.board_height - y))}}}' for x, y in pts)
    links = ' '.join(f'{{{a} {b}}}' for a, b in edges(pts))
    return (f'(board (graph vertices:{{{vertices}}} edges:{{{links}}}) use:Vertex)')


def start(mode):
    index = {p: i for i, p in enumerate(points(mode))}
    places = []
    for player, color in enumerate(mode.players, start=1):
        sites = ' '.join(str(index[p]) for p in sorted(mode.start_positions[color],
                                                         key=lambda p: (p[1], p[0])))
        places.append(f'(place "Disc{player}" (sites {{{sites}}}))')
    return '(start {' + ' '.join(places) + '})'


def colours(mode):
    return ' '.join(f'(player Colour P{player} (colour {" ".join(map(str, RGB[color]))}))'
                    for player, color in enumerate(mode.players, start=1))


def describe_players(mode):
    names = ', '.join(c.capitalize() for c in mode.players)
    pieces = '/'.join(str(len(mode.start_positions[c])) for c in mode.players)
    return f'{len(mode.players)} players ({names}, in turn order; {pieces} pieces).'


LUD = '''// Tactical Formation (Cờ Trận), a Vietnamese folk board game.
// Generated by tools/make_ludii.py from core/modes.py — edit that script, not this file.
// The folk game has no move limit. Ludii stops any game after its default limit
// of 1250 turns and scores the players still in as a draw; long 3- and 4-player
// games can reach it.

(define "Flanks"
    (forEach (sites Occupied by:Mover)
        if:(and
            (< 0 (count Sites in:(sites Between from:#1 to:(site))))
            (all Sites (sites Between from:#1 to:(site)) if:(is Enemy (who at:(site))))
        )
    )
)

(define "ChooseLine"
    (forEach Site ("Flanks" (last To))
        (move Select (from (site))
            (then
                (forEach Site (sites Between from:(var "Landing") to:(last To))
                    (and
                        (remove (site))
                        (add (piece (id "Disc" Mover)) (to (site)))
                    )
                )
            )
        )
    )
)

//------------------------------------------------------------------------------

(game "Tactical Formation"
    (players <Players:num>)
    (equipment {
        <Players:board>
        (piece "Disc" Each
            (move Hop
                (between if:(is Occupied (between)))
                (to if:(is Empty (to)))
                (then
                    (and
                        (set Var "Landing" (last To))
                        (if (can Move ("ChooseLine")) (moveAgain))
                    )
                )
            )
        )
    })
    (rules
        <Players:start>
        (play
            (if (is Prev Mover)
                ("ChooseLine")
                (forEach Piece)
            )
        )
        (end ("NoMoves" Loss))   // the player about to move has no jump: out
    )
)

//------------------------------------------------------------------------------

(option "Players" <Players> args:{ <num> <board> <start> <colours> } {
__OPTIONS__
})

//------------------------------------------------------------------------------

(metadata
    (info {
        (description "Tactical Formation (Cờ Trận in Vietnamese) is a folk board game played by children in Dong Bua hamlet, Tam Quan commune, Tam Dao district, Vinh Phuc province, Vietnam. The board was drawn on the road, and the pieces were stones, pebbles, twigs or leaves. Its creator is unknown; the rules were recorded in 2026 from the recollection of a former player.")
        (aliases {"Cờ Trận" "Co Tran"})
        (rules "The board is a grid of points with both diagonals drawn in every square; the centre of each square is also a point. Every move is a jump over one adjacent piece of any colour to the empty point straight beyond it: a grid point jumps along the grid lines, or diagonally over a centre to the opposite corner; a centre jumps diagonally over a corner to the next centre. The jumped piece stays. After landing, if enemy pieces in a straight line are closed off by one of the mover's pieces, that whole line changes to the mover's colour; if several lines are closed off, the mover chooses one (in this implementation, by selecting the own piece at the far end of the line). Captured pieces change colour; nothing is removed. A player who cannot move on their turn loses (with three or four players they are out, their pieces stay on the board and can still be captured). The last player left wins. There is no move limit and no draw.")
        (source "Truong, V. Q. (2026). Tactical Formation: Documenting and Analysing a Vietnamese Folk Board Game for 2-4 Players. Zenodo, <a href=\\"https://doi.org/10.5281/zenodo.23437471\\" target=\\"_blank\\" class=\\"style1\\" style=\\"color: #0000EE\\" />doi:10.5281/zenodo.23437471</a>")
        (version "1.3.14")
        (classification "board/war/custodial")
        (credit "Truong Van Quyet")
        (origin "This game was played in Vietnam, around 2011-2016.")
    })
    (graphics {
        <Players:colours>
    })
)
'''


def main():
    items = []
    for n, mode in MODES.items():
        default = '*' if n == 2 else ''
        items.append(
            f'    (item "{n}" <{n}>\n'
            f'        <{board(mode)}>\n'
            f'        <{start(mode)}>\n'
            f'        <{colours(mode)}>\n'
            f'        "{describe_players(mode)}"\n'
            f'    ){default}')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(LUD.replace('__OPTIONS__', '\n'.join(items)))
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
